namespace App\Entity\Traits;

use Doctrine\ORM\Mapping as ORM;

trait LogoableTrait
{
    #[ORM\Column(length: 100)]
    private ?string $logo = null;

    public function getLogo(): ?string
    {
        return $this->logo;
    }

    public function setLogo(string $logo): static
    {
        $this->logo = $logo;

        return $this;
    }
}
