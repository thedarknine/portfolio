<?php

declare(strict_types=1);

use Rector\Caching\ValueObject\Storage\FileCacheStorage;
use Rector\CodeQuality\Rector\Attribute\SortAttributeNamedArgsRector;
use Rector\CodeQuality\Rector\Concat\DirnameDirConcatStringToDirectStringPathRector;
use Rector\CodeQuality\Rector\FuncCall\SortCallLikeNamedArgsRector;
use Rector\CodeQuality\Rector\If_\ExplicitNullableObjectInstanceRector;
use Rector\Config\RectorConfig;
use Rector\Set\ValueObject\SetList;
use Rector\Symfony\CodeQuality\Rector\Class_\EventSubscriberToAttributeRector;

// https://getrector.com/documentation
$rootDir = __DIR__ . '/../..';

return RectorConfig::configure()
    ->withPaths([
        $rootDir . '/config',
        $rootDir . '/public',
        $rootDir . '/src',
        $rootDir . '/tests',
    ])
    ->withSkip([
        // Generated by Symfony, rewritten at each cache warmup
        $rootDir . '/config/reference.php',
        $rootDir . '/config/bundles.php',
        $rootDir . '/src/Kernel.php',
        // Generated by app:generate-fixtures (src/Command/GenerateFixturesCommand.php)
        $rootDir . '/src/DataFixtures/Testing',
        $rootDir . '/src/DataFixtures/*AutoFixture.php',
        $rootDir . '/tests/bootstrap.php',
        // null === $x is kept: instanceof checks on nullable properties add nothing (and use FQCN instead of self)
        ExplicitNullableObjectInstanceRector::class,
        // Front controller and preload file are Symfony recipe files: keep them as shipped
        DirnameDirConcatStringToDirectStringPathRector::class => [
            $rootDir . '/config/preload.php',
            $rootDir . '/public/index.php',
        ],
        // TODO: move SitemapSubscriber to #[AsEventListener] (and its test) in a dedicated change
        EventSubscriberToAttributeRector::class,
        // Named arguments keep the order chosen in the code
        SortAttributeNamedArgsRector::class,
        SortCallLikeNamedArgsRector::class,
    ])
    ->withCache(__DIR__ . '/../cache/rector', FileCacheStorage::class)

    // PHP version is read from composer.json (config.platform.php)
    ->withPhpSets()

    // Symfony, Twig, Doctrine and PHPUnit sets matching the installed versions
    ->withComposerBased(twig: true, doctrine: true, phpunit: true, symfony: true)
    ->withSymfonyContainerXml($rootDir . '/var/cache/dev/App_KernelDevDebugContainer.xml')

    // Convert annotations to attributes (routes, Doctrine mapping, constraints...)
    ->withAttributesSets()

    ->withSets([
        SetList::TYPE_DECLARATION,
        SetList::PRIVATIZATION,
    ])
    // No codingStyle set: php-cs-fixer owns the formatting (Yoda style, newlines, quotes...)
    ->withPreparedSets(
        deadCode: true,
        codeQuality: true,
        typeDeclarations: true,
        earlyReturn: true,
    )
    ->withImportNames(importShortClasses: false, removeUnusedImports: true)
;
