<?php

use Symfony\Component\Dotenv\Dotenv;

// PROJECT_NAME is read from .env (and .env.local if it exists), so the header follows the project
$rootDir = __DIR__ . '/../../';
$env     = [];
foreach (['.env', '.env.local'] as $file) {
    if (is_file($rootDir . $file)) {
        $env = array_merge($env, (new Dotenv())->parse((string) file_get_contents($rootDir . $file), $file));
    }
}
$projectName = $env['PROJECT_NAME'] ?? 'MyProject';

$header = <<<HEADER
This file is part of {$projectName} project.
(c) Caroline Noyer <studio@carolinenoyer.fr>

This source file is proprietary, all rights reserved.
See the LICENSE file bundled with this source code.
HEADER;

// https://cs.symfony.com/doc/rules/index.html
$finder = (new PhpCsFixer\Finder())
    ->in($rootDir)
    ->exclude([
        '.docker',
        // pnpm content-addressable store: ~46k files, too slow to walk through the Docker mount
        '.pnpm-store',
        '.tools',
        'assets',
        'config',
        'coverage',
        'node_modules',
        'public/assets',
        'public/build',
        'src/DataFixtures',
        'tmp',
        'var',
        'vendor',
    ])
    // Portfolio-only: the phparkitect config is PHP code too
    ->append([__DIR__ . '/phparkitect.php'])
    // Generated by "importmap:require", which rewrites it
    ->notPath('importmap.php')
;

return (new PhpCsFixer\Config())
    ->setRules([
        '@Symfony' => true,
        'header_comment' => [
            'header' => $header,
            'comment_type' => 'PHPDoc'
        ],

        // Manage imports order and remove unused imports
        'ordered_imports' => [
            'imports_order' => ['class', 'function', 'const'],
            'sort_algorithm' => 'alpha',
        ],
        'no_unused_imports' => true,

        // Order class elements
        'ordered_class_elements' => [
            'order' => [
                'use_trait',
                'case',
                'constant_public',
                'constant_protected',
                'constant_private',
                'property_public',
                'property_protected',
                'property_private',
                'construct',
                'destruct',
                'magic',
                'phpunit',
                'method_public',
                'method_protected',
                'method_private',
            ],
        ],

        // Yoda style, prefer `true === $value` over `$value === true`
        'yoda_style' => true,

        // Align vertical arrows `=>` in arrays and `=` assignments
        'binary_operator_spaces' => [
            'default' => 'single_space',
            'operators' => [
                '=>' => 'align_single_space',
                '='  => 'align_single_space',
            ],
        ],

        // Add space around concatenation operator (ex: $a . ' ' . $b)
        // By default, Symfony concatenates strings ($a.$b). Adding space makes the code more readable
        'concat_space' => ['spacing' => 'one'],

        // Trailing comma required for multiline arrays, arguments, and parameters
        // Ideal for clean Git diffs when adding an element
        'trailing_comma_in_multiline' => [
            'elements' => ['arrays', 'arguments', 'parameters'],
        ],

        // Add empty line before control structures for better readability
        'blank_line_before_statement' => [
            'statements' => ['break', 'continue', 'declare', 'return', 'throw', 'try'],
        ],

        // Force use of short syntax for arrays `[]` instead of `array()`
        'array_syntax' => ['syntax' => 'short'],

        // Clean up unnecessary blank lines (at the end of blocks, after trait declarations...)
        'no_extra_blank_lines' => [
            'tokens' => [
                'extra',
                'throw',
                'use',
            ],
        ],

        // Proper spacing for typed arguments and parameters (Nullable, etc.)
        'compact_nullable_type_declaration' => true,
        'type_declaration_spaces' => true,

        // Remove unnecessary PHPDoc tags
        'no_superfluous_phpdoc_tags' => [
            'allow_mixed' => true,
        ],

        // Convert PHPDoc to comment when possible
        'phpdoc_to_comment' => true,

        // Remove unnecessary else statements
        'no_useless_else' => true,

        // PHPDoc line span
        'phpdoc_line_span' => [
            'const'    => 'single',
            'property' => 'single',
            'method'   => 'multi',
        ],
    ])
    ->setFinder($finder)
    ->setCacheFile(__DIR__ . '/../cache/.php-cs-fixer.cache')
;
